def fetch_live_atm_option(ticker: str = "NVDA") -> Tuple[float, float, float, float]:
    """Fetches the nearest-expiry, at-the-money call from live market data.

    Falls back to the bid/ask midpoint when `lastPrice` is stale or zero,
    which is common for thinly traded strikes.
    """
    tkr = yf.Ticker(ticker)
    hist = tkr.history(period="1d")
    S0 = hist["Close"].iloc[-1]

    expirations = tkr.options
    if not expirations:
        raise ValueError("No options data available.")

    near_expiry = expirations[0]
    opt_chain = tkr.option_chain(near_expiry)
    calls = opt_chain.calls

    atm_call = calls.iloc[(calls["strike"] - S0).abs().argsort()[:1]]
    K = float(atm_call["strike"].values[0])
    last_price = float(atm_call["lastPrice"].values[0])
    bid = float(atm_call["bid"].values[0])
    ask = float(atm_call["ask"].values[0])

    market_price = (bid + ask) / 2.0 if (last_price <= 0 and bid > 0 and ask > 0) else last_price
    if market_price <= 0:
        raise ValueError(f"No usable quote for {ticker} {near_expiry} {K}C.")

    days_to_expiry = (pd.to_datetime(near_expiry) - pd.Timestamp.today()).days
    T = max(days_to_expiry / 365.0, 1 / 365.0)

    return S0, K, T, market_price


