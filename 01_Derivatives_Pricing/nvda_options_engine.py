"""
Option Pricing & Discrete Delta-Hedging Risk Engine
====================================================
Black-Scholes pricer with full analytical Greeks, Newton-Raphson implied
volatility extraction, and a Monte Carlo simulation of discrete
delta-hedging tracking error ("Gamma bleed") calibrated on live option
market data via yfinance.

Author: Emile Roumieux
"""

import numpy as np
import pandas as pd
import yfinance as yf
import matplotlib.pyplot as plt
from scipy.stats import norm
from typing import Dict, Tuple, Union

# =====================================================================
# 1. PRICING & GREEKS ENGINE
# =====================================================================

def vectorized_bs_greeks(
    S: Union[float, np.ndarray],
    K: float,
    T: Union[float, np.ndarray],
    r: float,
    sigma: float,
    option_type: str = "call",
) -> Dict[str, Union[float, np.ndarray]]:
    """Vectorized Black-Scholes pricer and analytical Greeks engine.

    Supports scalar or NumPy array inputs for S and T, so the same function
    prices a single option or an entire simulated path grid at once.
    """
    T_safe = np.maximum(T, 1e-5)
    d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T_safe) / (sigma * np.sqrt(T_safe))
    d2 = d1 - sigma * np.sqrt(T_safe)

    n_d1, n_d2, pdf_d1 = norm.cdf(d1), norm.cdf(d2), norm.pdf(d1)

    if option_type.lower() == "call":
        price = S * n_d1 - K * np.exp(-r * T_safe) * n_d2
        delta = n_d1
        theta = (-(S * pdf_d1 * sigma) / (2 * np.sqrt(T_safe)) - r * K * np.exp(-r * T_safe) * n_d2) / 365.0
        rho = K * T_safe * np.exp(-r * T_safe) * n_d2 / 100.0
    elif option_type.lower() == "put":
        price = K * np.exp(-r * T_safe) * norm.cdf(-d2) - S * norm.cdf(-d1)
        delta = n_d1 - 1.0
        theta = (-(S * pdf_d1 * sigma) / (2 * np.sqrt(T_safe)) + r * K * np.exp(-r * T_safe) * norm.cdf(-d2)) / 365.0
        rho = -K * T_safe * np.exp(-r * T_safe) * norm.cdf(-d2) / 100.0
    else:
        raise ValueError("option_type must be 'call' or 'put'")

    gamma = pdf_d1 / (S * sigma * np.sqrt(T_safe))
    vega = (S * np.sqrt(T_safe) * pdf_d1) / 100.0

    return {"price": price, "delta": delta, "gamma": gamma, "vega": vega, "theta": theta, "rho": rho}


def implied_vol_newton(
    market_price: float,
    S: float,
    K: float,
    T: float,
    r: float,
    option_type: str = "call",
    tol: float = 1e-6,
    max_iter: int = 100,
    sigma_bounds: Tuple[float, float] = (1e-4, 5.0),
) -> float:
    """Extracts implied volatility via Newton-Raphson.

    Bounds are enforced at every step: without them, a stale or zero
    quote can push sigma negative, which then crashes the downstream
    Monte Carlo simulation (np.random.normal rejects a negative scale).
    """
    sigma = 0.3  # reasonable seed for equities
    for _ in range(max_iter):
        res = vectorized_bs_greeks(S, K, T, r, sigma, option_type)
        diff = res["price"] - market_price
        if abs(diff) < tol:
            return float(np.clip(sigma, *sigma_bounds))

        raw_vega = res["vega"] * 100.0  # undo the 1%-move scaling to get the true derivative
        if abs(raw_vega) < 1e-8:
            break  # vega too flat to make progress (deep ITM/OTM or near expiry)

        sigma = float(np.clip(sigma - diff / raw_vega, *sigma_bounds))

    return sigma


def test_put_call_parity() -> None:
    """Validates the pricer against put-call parity: C - P = S - K*e^(-rT)."""
    S, K, T, r, sigma = 100.0, 100.0, 1.0, 0.05, 0.2
    c_price = vectorized_bs_greeks(S, K, T, r, sigma, "call")["price"]
    p_price = vectorized_bs_greeks(S, K, T, r, sigma, "put")["price"]
    assert np.isclose(c_price - p_price, S - K * np.exp(-r * T)), "Put-Call Parity failed!"
    print("Put-Call Parity test passed")


# =====================================================================
# 2. DISCRETE HEDGING & PnL SIMULATION
# =====================================================================

def simulate_discrete_hedging_pnl(
    S0: float,
    K: float,
    r: float,
    sigma: float,
    T: float,
    option_price: float,
    steps: int = 63,
    paths: int = 1000,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Simulates underlying paths and the P&L of a discretely rebalanced
    delta-hedge replicating a long call.

    The replicating portfolio is seeded with the option's actual traded
    premium (Pi_0 = option_price), not zero -- this is what makes the
    residual reflect pure discretization error ("Gamma bleed") instead of
    a missing-capital artifact roughly equal to the premium itself.

    Paths are simulated under the risk-neutral measure (drift = r), and the
    same sigma is used both to generate paths and to compute hedge ratios.
    This isolates the effect of discrete vs. continuous rebalancing from
    any model or volatility misspecification.
    """
    dt = T / steps
    np.random.seed(42)

    increments = np.random.normal(
        loc=(r - 0.5 * sigma ** 2) * dt, scale=sigma * np.sqrt(dt), size=(paths, steps)
    )
    log_paths = np.zeros((paths, steps + 1))
    log_paths[:, 1:] = np.cumsum(increments, axis=1)
    S_paths = S0 * np.exp(log_paths)

    time_grid = np.linspace(T, 1e-5, steps + 1)
    deltas = np.zeros((paths, steps + 1))
    for t_idx in range(steps + 1):
        deltas[:, t_idx] = vectorized_bs_greeks(S_paths[:, t_idx], K, time_grid[t_idx], r, sigma, "call")["delta"]

    # Self-financing replicating portfolio, seeded with the option premium
    # (the fix): Pi_0 = delta_0 * S_0 + cash_0 = option_price.
    cash = option_price - deltas[:, 0] * S_paths[:, 0]
    for t in range(1, steps + 1):
        cash = cash * np.exp(r * dt) - (deltas[:, t] - deltas[:, t - 1]) * S_paths[:, t]

    portfolio_value = deltas[:, -1] * S_paths[:, -1] + cash
    payoff = np.maximum(S_paths[:, -1] - K, 0)
    tracking_error = payoff - portfolio_value  # residual "Gamma bleed"

    return S_paths, deltas, tracking_error


